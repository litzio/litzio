import { HEALTH_CHECK_OUTPUT_SCHEMA, SDK_VERSION } from "@litzio/plugin-sdk";
import { ISSUE_COLUMNS, type BuilderSpec } from "../shared/plugin-builder.ts";

/**
 * Deterministic plugin generator. The assistant never writes plugin code: it only fills a
 * validated BuilderSpec, and this template turns the spec into a manifest and host entry
 * that use the public SDK alone (same shape as community-plugins/jira).
 */
const COLUMN_LABEL: Record<(typeof ISSUE_COLUMNS)[number], string> = { number: "번호", title: "제목", state: "상태", author: "작성자", labels: "라벨", assignee: "담당자", comments: "댓글", updated: "수정일", created: "생성일" };
const object = (properties: Record<string, unknown>, required: string[] = []) => ({ type: "object", properties, ...(required.length ? { required } : {}), additionalProperties: false });

export function generationIssue(spec: BuilderSpec): string | undefined {
  if (spec.template !== "github-issues") return "이 스파이크의 생성기는 github-issues 템플릿만 지원해요.";
  if (spec.auth !== "none") return "토큰이 필요한 플러그인은 Linux Host에서 비밀값을 저장할 수 없어 이번 생성기에서 만들지 않아요(Windows Host 전용).";
  if (!spec.repo) return "저장소(owner/name)가 정해지지 않았어요.";
  if (!spec.columns.length) return "표시할 열이 정해지지 않았어요.";
  return undefined;
}

export function githubIssuesPlugin(spec: BuilderSpec, id: string) {
  const columns = ISSUE_COLUMNS.filter(column => spec.columns.includes(column));
  if (!columns.includes("number")) columns.unshift("number");
  const rowSchema = Object.fromEntries([...ISSUE_COLUMNS, "url" as const].map(key => [key, key === "url" ? { type: "string", label: "이슈 페이지 URL", hidden: true }
    : { type: "string", label: COLUMN_LABEL[key], ...(key === "number" ? { linkField: "url" } : {}), ...(columns.includes(key) ? {} : { hidden: true }) }]));
  const row = object({ ...Object.fromEntries([...ISSUE_COLUMNS, "url"].map(key => [key, { type: "string" }])) }, [...ISSUE_COLUMNS, "url"]);
  const input = object({
    state: { type: "string", title: "상태", enum: ["열림", "닫힘", "전체"] },
    labels: { type: "string", title: "라벨", description: "선택: 쉼표로 구분한 라벨 이름.", maxLength: 120 },
    assignee: { type: "string", title: "담당자", description: "선택: GitHub 사용자 이름.", maxLength: 60, pattern: "^[A-Za-z0-9-]*$" },
    repo: { type: "string", title: "저장소", description: "선택: owner/name. 비우면 설정의 저장소를 써요.", maxLength: 140, pattern: "^([A-Za-z0-9][A-Za-z0-9-]{0,38}/[A-Za-z0-9._-]{1,100})?$" },
  });
  const manifest = {
    schemaVersion: 1, id, tier: "community", publisher: { id: "local", name: "Local author" },
    name: spec.pluginName || "GitHub 이슈", description: `${spec.repo} 저장소의 GitHub 이슈를 읽기 전용으로 조회합니다. 토큰이 필요 없어요.`,
    version: "0.1.0", requiresSdk: `>=${SDK_VERSION} <1.0.0`, entry: "host.js",
    settingsSchema: object({ repo: { type: "string", title: "저장소", description: "owner/name 형식의 공개 저장소", default: spec.repo, minLength: 3 } }),
    contributes: {
      healthCheck: "connection",
      operations: [
        { id: "issues", version: 1, effect: "read", scope: "host", assistant: true, inputSchema: input,
          outputSchema: object({ rows: { type: "array", maxItems: 100, items: row }, truncated: { type: "boolean" }, total: { type: "integer", minimum: 0 } }, ["rows", "truncated"]), rowSchema },
        { id: "connection", version: 1, effect: "read", scope: "host", assistant: false, inputSchema: object({}), outputSchema: HEALTH_CHECK_OUTPUT_SCHEMA },
      ],
      views: [{ id: "issues", title: "이슈 조회", definition: {
        kind: "litzio-view", schemaVersion: 2, catalog: "litzio-v2", profile: "query", owner: id, title: `${spec.pluginName || "GitHub 이슈"} 조회`, refresh: "manual",
        sources: { stats: { kind: "operation", operation: `${id}.issues`, version: 1, args: { state: ({ open: "열림", closed: "닫힘", all: "전체" } as const)[spec.state], ...(spec.labels ? { labels: spec.labels } : {}), ...(spec.assignee ? { assignee: spec.assignee } : {}) } } },
        layout: { component: "Panel", direction: "vertical", children: [{ component: "Table", title: `${spec.repo} 이슈`, source: "stats", data: "/rows", columns }] },
        form: { component: "InputForm", source: "stats", fields: [{ component: "Select", field: "state" }, { component: "TextInput", field: "labels" }, { component: "TextInput", field: "assignee" }, { component: "TextInput", field: "repo", advanced: true }], submit: { component: "SubmitButton", label: "조회" } },
      } }],
      screens: [{ id: "issues", title: spec.pluginName || "GitHub 이슈", icon: "Table", defaultViewIds: ["issues"], primary: true }],
    },
  };
  return { manifest, source: hostSource(spec.pageSize) };
}

function hostSource(pageSize: number): string {
  return `import { PluginOperationError } from "@litzio/plugin-sdk";

// Generated by the Litzio plugin builder spike from a validated spec. Read-only, public GitHub REST API, no token.
const DEADLINE_MS = 8000;
const PAGE_SIZE = ${Math.min(30, Math.max(1, Math.trunc(pageSize)))};
const STATES = { 열림: "open", 닫힘: "closed", 전체: "all" };
const REPO = /^[A-Za-z0-9][A-Za-z0-9-]{0,38}\\/[A-Za-z0-9._-]{1,100}$/;
const text = value => typeof value === "string" && value.trim() ? value : "—";
const day = value => typeof value === "string" && /^\\d{4}-\\d{2}-\\d{2}T/.test(value) ? value.slice(0, 10) : "—";
const kind = status => status === 401 ? "auth" : status === 403 || status === 429 ? "forbidden" : status === 404 ? "not_found" : status >= 500 ? "unavailable" : "failed";
const headers = { Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "litzio-plugin" };

/** @param {import("@litzio/plugin-sdk").PluginContext} context */
export function activate(context) {
  const requests = new Set();
  const repoOf = input => {
    const repo = String(input?.repo ?? "").trim() || String(context.settings.repo ?? "").trim();
    if (!REPO.test(repo)) throw new PluginOperationError("failed");
    return repo;
  };
  async function get(url) {
    const controller = new AbortController(); requests.add(controller);
    const timer = setTimeout(() => controller.abort(), DEADLINE_MS);
    try {
      const response = await fetch(url, { headers, signal: controller.signal, redirect: "error" });
      if (!response.ok) { await response.body?.cancel(); throw new PluginOperationError(kind(response.status)); }
      return await response.json();
    } catch (error) {
      if (controller.signal.aborted) throw new PluginOperationError("timeout");
      if (error instanceof PluginOperationError) throw error;
      throw new PluginOperationError("failed");
    } finally { clearTimeout(timer); requests.delete(controller); }
  }
  return {
    operations: {
      async issues(input = {}) {
        const repo = repoOf(input);
        const choice = input.state ?? "열림";
        if (typeof choice !== "string" || !Object.hasOwn(STATES, choice)) throw new PluginOperationError("failed");
        const state = STATES[choice];
        const query = new URLSearchParams({ state, per_page: String(PAGE_SIZE), sort: "updated", direction: "desc" });
        if (typeof input.labels === "string" && input.labels.trim()) query.set("labels", input.labels.trim());
        if (typeof input.assignee === "string" && input.assignee.trim()) query.set("assignee", input.assignee.trim());
        const body = await get("https://api.github.com/repos/" + repo + "/issues?" + query);
        if (!Array.isArray(body)) throw new PluginOperationError("failed");
        // The issues endpoint also lists pull requests; this plugin shows issues only.
        const rows = body.filter(item => item && !item.pull_request && Number.isSafeInteger(item.number)).map(item => ({
          number: "#" + item.number, title: text(item.title), state: text(item.state), author: text(item.user?.login),
          labels: text(Array.isArray(item.labels) ? item.labels.map(label => label?.name).filter(Boolean).join(", ") : ""),
          assignee: text(item.assignee?.login), comments: String(Number.isSafeInteger(item.comments) ? item.comments : 0),
          updated: day(item.updated_at), created: day(item.created_at),
          url: typeof item.html_url === "string" && item.html_url.startsWith("https://github.com/") ? item.html_url : "https://github.com/" + repo + "/issues/" + item.number,
        }));
        // GitHub reports no total: say "more exist" when the page is full, otherwise the exact count.
        return body.length >= PAGE_SIZE ? { rows, truncated: true } : { rows, truncated: false, total: rows.length };
      },
      async connection() {
        const result = (ok, message) => ({ ok, message });
        let repo;
        try { repo = repoOf({}); } catch { return result(false, "저장소를 owner/name 형식으로 입력하세요."); }
        try {
          const body = await get("https://api.github.com/repos/" + repo);
          return body?.full_name ? result(true, repo + " 저장소에 연결했어요. (토큰 없음, 읽기 전용)") : result(false, "GitHub 응답 형식을 확인하세요.");
        } catch (error) {
          return result(false, error instanceof PluginOperationError && error.kind === "not_found" ? "저장소를 찾을 수 없어요. 공개 저장소인지 확인하세요. (404)" : error instanceof PluginOperationError && error.kind === "forbidden" ? "GitHub 요청 한도에 도달했을 수 있어요. 잠시 후 다시 시도하세요. (403)" : "GitHub에 연결할 수 없어요. 네트워크를 확인하세요.");
        }
      },
    },
    status: () => ({ available: true, message: "공개 GitHub API · 읽기 전용", folders: [], decorations: [], accounts: [] }),
    dispose() { for (const controller of requests) controller.abort(); requests.clear(); },
  };
}
`;
}

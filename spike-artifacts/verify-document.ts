import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import assert from 'node:assert/strict';
import { parse, serialize, validateStructure } from '../packages/core/src/index.ts';
import { RootAccess } from '../apps/editor/server/file-access.ts';
import { executeDocumentTool } from '../apps/editor/server/assistant-document-tools.ts';
const session=JSON.parse(readFileSync(new URL('./session.json',import.meta.url),'utf8'));
const root=path.resolve(import.meta.dirname,'documents'), file=path.join(root,session.document.name);
const source=readFileSync(file,'utf8'), digest=()=>createHash('sha256').update(readFileSync(file)).digest('hex');
const before=digest(); validateStructure(parse(source)); assert.equal(serialize(parse(source)),source);
const access=new RootAccess([root]);
const scope={folders:access,access,permissionMode:'opened-folders'};
assert.throws(()=>executeDocumentTool('create_document',{path:file,title:'Overwrite probe',blocks:[]},scope),/already exists/);
assert.equal(digest(),before);
const reread:any=executeDocumentTool('read_document',{path:file},scope);
assert.equal(reread.revision,session.document.revision); assert.equal(reread.source,session.document.source);
writeFileSync(new URL('./file-verification.json',import.meta.url),JSON.stringify({valid:true,canonical:true,overwriteRefused:true,hashUnchanged:true,sha256:before,revisionMatches:true},null,2));
console.log('Native reread, canonical validity, exclusive creation and unchanged hash: PASS');
